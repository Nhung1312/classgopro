/**
 * Returns a random team preset with exclusion of current preset if provided
 */
export function getRandomTeamPreset(currentPresetId?: string): ArenaTeamPreset {
  const candidates = currentPresetId
    ? ARENA_TEAM_PRESETS.filter((p) => p.id !== currentPresetId)
    : ARENA_TEAM_PRESETS;
  const pool = candidates.length > 0 ? candidates : ARENA_TEAM_PRESETS;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
