import { strict as assert } from 'node:assert';
import { applyMysteryDoorAssessment as record } from '../src/utils/mysteryDoorAssessment';
import type { ClassRoom, HistoryRecord, QuestionItem } from '../src/types';
const student = { id:'s1', name:'An', callCount:4, scores:{tx1:0, tx2:null} };
const cls:ClassRoom={ id:'c1', name:'7A1', subject:'Toán', students:[student], createdAt:'2026-01-01' };
const q:QuestionItem={id:'q1',content:'Tính 2+2'};
const at=new Date('2026-10-22T10:00:00.000Z');
const make=(classes:ClassRoom[],history:HistoryRecord[],attemptId:string,change:Parameters<typeof record>[0]['change']) =>
 record({classes,history,classId:'c1',studentId:'s1',question:q,attemptId,mode:'FAIR',change,timestamp:at});
const status=make([cls],[],'review-a',{outcome:'Đạt'});
assert.equal(status.saved,true);
assert.equal(status.history.length,1);
assert.equal(status.classes[0].students[0].callCount,4);
assert.equal(status.history[0].score,undefined);
const scored=make(status.classes,status.history,'review-a',{score:8.5,saveToGradebook:true});
assert.equal(scored.saved,true);
assert.equal(scored.history.length,1,'status and score share record');
assert.equal(scored.history[0].note,'Ô cửa bí mật: Đạt');
assert.equal(scored.history[0].score,'8.5');
assert.equal(scored.classes[0].students[0].callCount,4);
assert.equal(scored.classes[0].students[0].scores?.tx1,0,'existing zero is kept');
assert.equal(scored.classes[0].students[0].scores?.tx2,8.5);
assert.equal(scored.history[0].assignedTxSlot,'tx2');
const twice=make(scored.classes,scored.history,'review-a',{score:9,saveToGradebook:true});
assert.equal(twice.saved,false);
assert.equal(twice.classes[0].students[0].scores?.tx3,undefined);
const independent=make([cls],[],'review-b',{score:0,saveToGradebook:false});
assert.equal(independent.saved,true);
assert.equal(independent.classes[0].students[0].scores?.tx2,null,'history-only score does not touch gradebook');
assert.equal(independent.history[0].score,'0');
const finalRating=make(independent.classes,independent.history,'review-b',{outcome:'Chưa đạt'});
assert.equal(finalRating.saved,true);
assert.equal(finalRating.history.length,1);
assert.equal(finalRating.history[0].score,'0');
const full:ClassRoom={...cls,students:[{...student,scores:{tx1:0,tx2:6,tx3:7,tx4:8}}]};
const overflow=make([full],[],'review-c',{score:9,saveToGradebook:true});
assert.equal(overflow.saved,false);
assert.equal(overflow.history.length,0);
assert.equal(make([cls],[],'review-x',{score:10.25}).saved,false);
assert.equal(make([cls],[],'review-x',{score:-1}).saved,false);
assert.equal(make([cls],[],'review-x',{score:11}).saved,false);
const collisions=make(scored.classes,scored.history,'review-a',{outcome:'Chưa đạt'});
assert.equal(collisions.saved,false,'cannot assess twice');
console.log('Review score tests passed: history-only, TX slot, zero, double save, calls, full slots.');
